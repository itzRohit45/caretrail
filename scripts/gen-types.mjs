// Generates src/lib/db/types.ts from the live schema (the Supabase CLI generator needs Docker).
// Usage: node --env-file=.env.local scripts/gen-types.mjs
import { writeFile } from "node:fs/promises";
import pg from "pg";

const client = new pg.Client({ connectionString: process.env.SUPABASE_DB_URL, ssl: { rejectUnauthorized: false } });
await client.connect();
const q = async (sql) => (await client.query(sql)).rows;

const cols = await q(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable = 'YES' as nullable,
         (c.column_default is not null or c.is_identity = 'YES' or c.is_generated = 'ALWAYS') as has_default
  from information_schema.columns c
  join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE' and c.table_name not like '\\_%'
  order by c.table_name, c.ordinal_position`);
const fks = await q(`
  select tc.constraint_name, tc.table_name, kcu.column_name, ccu.table_name as ref_table, ccu.column_name as ref_column
  from information_schema.table_constraints tc
  join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
  join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name and ccu.table_schema = tc.table_schema
  where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public' and ccu.table_schema = 'public'`);
await client.end();

const scalar = (udt) => {
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(udt)) return "number";
  if (udt === "bool") return "boolean";
  if (["json", "jsonb"].includes(udt)) return "Json";
  return "string";
};
const tsType = (c) => (c.data_type === "ARRAY" ? `${scalar(c.udt_name.slice(1))}[]` : scalar(c.udt_name));

const tables = {};
for (const c of cols) (tables[c.table_name] ??= []).push(c);

let out = `// Generated by scripts/gen-types.mjs from the live schema. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, cs] of Object.entries(tables)) {
  const row = cs.map((c) => `          ${c.column_name}: ${tsType(c)}${c.nullable ? " | null" : ""};`).join("\n");
  const ins = cs
    .map((c) => `          ${c.column_name}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c)}${c.nullable ? " | null" : ""};`)
    .join("\n");
  const upd = cs.map((c) => `          ${c.column_name}?: ${tsType(c)}${c.nullable ? " | null" : ""};`).join("\n");
  const rel = fks
    .filter((f) => f.table_name === name)
    .map(
      (f) =>
        `          { foreignKeyName: "${f.constraint_name}"; columns: ["${f.column_name}"]; isOneToOne: false; referencedRelation: "${f.ref_table}"; referencedColumns: ["${f.ref_column}"] },`,
    )
    .join("\n");
  out += `      ${name}: {
        Row: {
${row}
        };
        Insert: {
${ins}
        };
        Update: {
${upd}
        };
        Relationships: [
${rel}
        ];
      };
`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
      rate_limit_hit: { Args: { p_key: string; p_limit: number; p_window_seconds: number }; Returns: boolean };
      owns_patient: { Args: { pid: string }; Returns: boolean };
      clone_demo_patient: { Args: { p_template: string; p_owner: string }; Returns: string };
    };
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicTables = Database["public"]["Tables"];
export type Row<T extends keyof PublicTables> = PublicTables[T]["Row"];
export type Insert<T extends keyof PublicTables> = PublicTables[T]["Insert"];
`;
await writeFile(new URL("../src/lib/db/types.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(tables).length} tables`);
