// Builds supabase/migrations/0003_drug_interactions.sql from the DDInter download CSVs,
// keeping only pairs among CareTrail's curated generics. Raw CSVs are not committed.
// Source: DDInter (https://ddinter.scbdd.com), Xiong G. et al., Nucleic Acids Research 2022.
// Usage: node scripts/build-interactions.mjs <dir-with-ddinter_downloads_code_*.csv>
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("pass the folder containing the DDInter CSV files");

// Our generic name -> DDInter name, where they differ. Everything else matches case-insensitively.
const ALIAS = { aspirin: "acetylsalicylic acid", paracetamol: "acetaminophen", torsemide: "torasemide" };
const seed = await readFile(new URL("../supabase/migrations/0002_reference_drugs.sql", import.meta.url), "utf8");
const generics = [...seed.matchAll(/^\s*\('([a-z0-9 -]+)', '[^']*', '[a-z]+'\)/gm)].map((m) => m[1]);
const byDdinterName = new Map(generics.map((g) => [ALIAS[g] ?? g, g]));

const RANK = { minor: 1, moderate: 2, major: 3 };
const pairs = new Map();
for (const file of (await readdir(dir)).filter((f) => f.endsWith(".csv"))) {
  const lines = (await readFile(join(dir, file), "utf8")).split(/\r?\n/).slice(1);
  for (const line of lines) {
    const [, drugA, , drugB, level] = line.split(",");
    const a = byDdinterName.get(drugA?.toLowerCase());
    const b = byDdinterName.get(drugB?.toLowerCase());
    const sev = level?.trim().toLowerCase();
    if (!a || !b || a === b || !(sev in RANK)) continue;
    const [x, y] = [a, b].sort();
    const key = `${x}|${y}`;
    if (!pairs.has(key) || RANK[sev] > RANK[pairs.get(key)]) pairs.set(key, sev);
  }
}

const rows = [...pairs.entries()].sort().map(([k, sev]) => {
  const [x, y] = k.split("|");
  return `  ('${x}', '${y}', '${sev}', 'DDInter')`;
});
const sql = `-- Drug-drug interaction pairs from DDInter (https://ddinter.scbdd.com; Xiong et al., NAR 2022),
-- filtered to the generics in 0002. Generated by scripts/build-interactions.mjs. ${rows.length} pairs.
-- DDInter severity levels are kept as published; pairs marked "Unknown" are excluded.

insert into public.drug_interactions (generic_a, generic_b, severity, source) values
${rows.join(",\n")}
on conflict (generic_a, generic_b) do update set severity = excluded.severity, source = excluded.source;
`;
await writeFile(new URL("../supabase/migrations/0003_drug_interactions.sql", import.meta.url), sql);
const counts = [...pairs.values()].reduce((m, s) => ({ ...m, [s]: (m[s] ?? 0) + 1 }), {});
console.log(`generics: ${generics.length}, pairs: ${rows.length}`, counts);
for (const k of ["clopidogrel|omeprazole", "aspirin|telmisartan", "amlodipine|atorvastatin", "metformin|telmisartan", "aspirin|clopidogrel", "ramipril|telmisartan"]) console.log(k, pairs.get(k) ?? "-");
